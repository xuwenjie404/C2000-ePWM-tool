import type { GeneratedFile, ProjectState } from '../../types';
import type { HardwareModel } from '../hardware';
import { fswRange } from '../runtimeApi';

/**
 * 运行时参数 API（epwm_api.c / epwm_api.h）。
 *
 * 目标：让下游代码只面对「频率 / 占空比 / 相位」这三个物理量，
 * 不碰 TBPRD / CMPA / TBPHS 的换算，也不用改初始化代码。
 *
 * 关键点（也是必须由库维护而不是用户手写的原因）：
 *   1. 改 TBPRD 会让旧的 CMPA 对应到新的占空比 —— 必须按占空比重新派生；
 *   2. 改 TBPRD 也会改变 TBPHS 的物理角度 —— 必须按相角重新派生；
 *   3. CMPA 需要夹在 [1, TBPRD-1]，否则输出恒定、死区后没有脉宽。
 */

function cNum(v: number, decimals = 1): string {
  return v.toFixed(decimals) + 'f';
}

function channelCases(
  hw: HardwareModel,
  body: (id: number) => string,
): string {
  return hw.channels
    .filter(c => c.cfg.enabled)
    .map(c => `        case ${c.cfg.id}U: ${body(c.cfg.id)} break;`)
    .join('\n');
}

function headerFile(project: ProjectState, hw: HardwareModel): string {
  const isCN = project.commentLang === 'CN';
  const chCount = hw.channels.filter(c => c.cfg.enabled).length;
  const upDown = project.countMode === 'UP_DOWN';
  const range = fswRange(hw.device.tbclkMHz, hw.master.tb.totalDiv, project.countMode);

  return `/**
 * @file    epwm_api.h
 * @brief   ${isCN ? 'ePWM 运行时参数 API：用物理量修改频率 / 占空比 / 相位' : 'ePWM runtime parameter API: change fsw / duty / phase by physical units'}
 *
 * ${isCN ? '本文件由 C2000 ePWM Tool 生成。下游控制代码只需包含它，' : 'Generated by C2000 ePWM Tool.'}
 * ${isCN ? '不必再关心 TBPRD / CMPA / TBPHS 之间的换算关系。' : ''}
 *
 * ${isCN ? '保证：' : 'Guarantees:'}
 *   ${isCN ? '· 改频率时自动按原占空比与相角重算 CMPA / TBPHS，语义不变；' : '· changing fsw keeps the same duty and phase semantics;'}
 *   ${isCN ? '· CMPA 始终夹在 [1, TBPRD-1]，不会出现恒定输出；' : '· CMPA is clamped to [1, TBPRD-1];'}
 *   ${isCN ? '· 所有写入都进影子寄存器，在下一个 CTR=0 / 同步事件生效，无毛刺。' : '· all writes hit shadow registers, applied at the next CTR=0 / sync.'}
 *
 * ${isCN ? '注意：分频 CLKDIV/HSPCLKDIV 在初始化时固定，本 API 只改 TBPRD。' : 'Note: CLKDIV/HSPCLKDIV are fixed at init; only TBPRD is changed at runtime.'}
 * ${isCN ? '      当前分频下的频率范围见下方两个宏。' : '      See the macros below for the achievable range.'}
 */
#ifndef EPWM_API_H
#define EPWM_API_H

#include <stdint.h>

#define EPWM_API_CH_COUNT    ${chCount}U
#define EPWM_API_TBCLK_HZ    ${hw.device.tbclkMHz * 1e6}f
#define EPWM_API_TOTAL_DIV   ${hw.master.tb.totalDiv}U
#define EPWM_API_UP_DOWN     ${upDown ? 1 : 0}U
#define EPWM_API_DUTY_MIN    0.5f
#define EPWM_API_DUTY_MAX    99.5f
${isCN ? '/* 当前分频下的寄存器极限；实际可用上限还受最小脉宽与死区约束 */' : '/* register limits at the current divider; real limits depend on min pulse and dead-band */'}
#define EPWM_API_FSW_MIN_KHZ ${cNum(range.minKhz, 4)}
#define EPWM_API_FSW_MAX_KHZ ${cNum(range.maxKhz, 2)}

/** ${isCN ? '单个通道的可调参数' : 'Per-channel parameters'} */
typedef struct
{
    float    fswKhz;    /**< ${isCN ? '开关频率，kHz' : 'switching frequency, kHz'} */
    float    dutyPct;   /**< ${isCN ? 'ePWMxA 占空比，%' : 'ePWMxA duty, %'} */
    float    phaseDeg;  /**< ${isCN ? '相对主通道移相角，0~360°' : 'phase shift vs master, 0..360 deg'} */
    uint16_t tbprd;     /**< ${isCN ? '当前 TBPRD（由频率派生，只读意义）' : 'current TBPRD (derived from fsw)'} */
    uint16_t syncEn;    /**< ${isCN ? '1 = 参与移相同步' : '1 = phase-sync enabled'} */
} EPWM_API_Param;

${isCN ? '/* 频率：同时按原占空比与相角重算派生值 */' : '/* frequency: re-derives duty and phase for the same semantics */'}
void  EPWM_setFrequency(unsigned int ch, float fswKhz);
${isCN ? '/* 占空比：% ，自动夹紧并换算成当前 TBPRD 下的 CMPA */' : '/* duty in %, clamped and converted to CMPA */'}
void  EPWM_setDuty(unsigned int ch, float dutyPct);
${isCN ? '/* 相位：0~360°，自动选择 PHSDIR 并换算 TBPHS；主通道与非同步通道忽略 */' : '/* phase 0..360 deg; ignored for master/independent channels */'}
void  EPWM_setPhase(unsigned int ch, float phaseDeg);
${isCN ? '/* 一次性写入整组参数，适合闭环里成组更新 */' : '/* apply a whole parameter set at once */'}
void  EPWM_setParam(unsigned int ch, const EPWM_API_Param *p);

const EPWM_API_Param *EPWM_getParam(unsigned int ch);
float    EPWM_actualFswKhz(unsigned int ch);
uint16_t EPWM_lastCmpa(unsigned int ch);

#endif /* EPWM_API_H */
`;
}

function sourceFile(project: ProjectState, hw: HardwareModel): string {
  const isCN = project.commentLang === 'CN';
  const t = (cn: string, en: string) => (isCN ? cn : en);
  const style = project.codeTarget;
  const isBitfield = style === 'BITFIELD';
  const channels = hw.channels.filter(c => c.cfg.enabled);

  const initRows = channels
    .map(c => {
      const tbprd = c.tb.tbprd;
      return `    { ${cNum(c.targetFreqKhz, 4)}, ${cNum(c.cfg.duty, 2)}, ${cNum(c.cfg.phase, 1)}, ${tbprd}U, ${
        c.syncEnabled ? 1 : 0
      }U }  /* ePWM${c.cfg.id} */`;
    })
    .join(',\n');

  const setTbprd = isBitfield
    ? channelCases(hw, id => `EPwm${id}Regs.TBPRD = (uint16_t)v;`)
    : channelCases(hw, id => `EPWM_setTimeBasePeriod(EPWM${id}_BASE, (uint16_t)v);`);

  const setCmpa = isBitfield
    ? channelCases(hw, id => `EPwm${id}Regs.CMPA.bit.CMPA = (uint16_t)v;`)
    : channelCases(hw, id => `EPWM_setCounterCompareValue(EPWM${id}_BASE, EPWM_COUNTER_COMPARE_A, (uint16_t)v);`);

  const setTbphs = isBitfield
    ? channelCases(hw, id => `EPwm${id}Regs.TBPHS.bit.TBPHS = (uint16_t)v;`)
    : channelCases(hw, id => `EPWM_setPhaseShift(EPWM${id}_BASE, (uint16_t)v);`);

  const setPhsdir = isBitfield
    ? channelCases(hw, id => `EPwm${id}Regs.TBCTL.bit.PHSDIR = v ? TB_UP : TB_DOWN;`)
    : channelCases(
        hw,
        id => `EPWM_setCountModeAfterSync(EPWM${id}_BASE, v ? EPWM_COUNT_MODE_UP_AFTER_SYNC : EPWM_COUNT_MODE_DOWN_AFTER_SYNC);`,
      );

  const readTbprd = isBitfield
    ? channelCases(hw, id => `tbprd = EPwm${id}Regs.TBPRD;`)
    : channelCases(hw, id => `tbprd = (uint16_t)HWREGH(EPWM${id}_BASE + EPWM_O_TBPRD);`);

  return `/**
 * @file    epwm_api.c
 * @brief   ${t('ePWM 运行时参数 API 实现', 'ePWM runtime parameter API implementation')}
 *
 * ${t('由 C2000 ePWM Tool 生成。换算公式与工具内的 runtimeApi.ts 一一对应，', 'Generated by C2000 ePWM Tool; formulas mirror runtimeApi.ts.')}
 * ${t('并由单元测试保证两者结果一致。', 'Unit tests keep both implementations in sync.')}
 */
${
  isBitfield
    ? `#include "F28x_Project.h"`
    : `#include "driverlib.h"\n#include "device.h"`
}
#include "epwm_api.h"

/** ${t('每个通道的当前参数（改频率时据此保持占空比与相角）', 'current per-channel parameters, used to preserve duty/phase on fsw change')} */
static EPWM_API_Param g_param[EPWM_API_CH_COUNT] =
{
${initRows}
};

/** ${t('最近一次写入的 CMPA，供闭环调试观察', 'last CMPA written, handy when debugging a control loop')} */
static uint16_t g_lastCmpa[EPWM_API_CH_COUNT] = { 0U };

/* ------------------------------------------------------------------ */
/* ${t('换算：与 runtimeApi.ts 保持一致，改动请两边同步', 'conversions: keep in sync with runtimeApi.ts')} */
/* ------------------------------------------------------------------ */

static uint16_t EPWM_apiTbprdFromFsw(float fswKhz)
{
    float f = fswKhz * 1000.0f;
    float raw;

    if (f < 1.0f) { f = 1.0f; }
#if EPWM_API_UP_DOWN
    raw = (EPWM_API_TBCLK_HZ / (float)EPWM_API_TOTAL_DIV) / (2.0f * f);
#else
    raw = (EPWM_API_TBCLK_HZ / (float)EPWM_API_TOTAL_DIV) / f - 1.0f;
#endif
    if (raw < 1.0f)     { raw = 1.0f; }
    if (raw > 65535.0f) { raw = 65535.0f; }
    return (uint16_t)(raw + 0.5f);
}

static uint16_t EPWM_apiCmpaFromDuty(float pct, uint16_t tbprd)
{
    float span;
    float c;

    if (pct < EPWM_API_DUTY_MIN) { pct = EPWM_API_DUTY_MIN; }
    if (pct > EPWM_API_DUTY_MAX) { pct = EPWM_API_DUTY_MAX; }
#if EPWM_API_UP_DOWN
    span = (float)tbprd;
#else
    span = (float)tbprd + 1.0f;
#endif
    c = pct * 0.01f * span;
    if (c < 1.0f)                    { c = 1.0f; }
    if (c > (float)(tbprd - 1U))     { c = (float)(tbprd - 1U); }
    return (uint16_t)(c + 0.5f);
}

static uint16_t EPWM_apiTbphsFromDeg(float deg, uint16_t tbprd, uint16_t *phsdirUp)
{
    float d = deg;
    float periodTicks;
    float delayTicks;
    float v;

    while (d < 0.0f)      { d += 360.0f; }
    while (d >= 360.0f)   { d -= 360.0f; }

#if EPWM_API_UP_DOWN
    periodTicks = 2.0f * (float)tbprd;
    delayTicks  = (d / 360.0f) * periodTicks;
    if (d <= 180.0f)
    {
        *phsdirUp = 0U;
        v = delayTicks;
    }
    else
    {
        *phsdirUp = 1U;
        v = periodTicks - delayTicks;
    }
#else
    periodTicks = (float)tbprd + 1.0f;
    delayTicks  = (d / 360.0f) * periodTicks;
    *phsdirUp   = 1U;
    v = periodTicks - delayTicks;
#endif

    if (v < 0.0f)              { v = 0.0f; }
    if (v > (float)tbprd)      { v = (float)tbprd; }
    return (uint16_t)(v + 0.5f);
}

/* ------------------------------------------------------------------ */
/* ${t('寄存器写入：按通道分发，两种代码风格各一组', 'register writes dispatched per channel, one set per code style')} */
/* ------------------------------------------------------------------ */

static void EPWM_apiWriteTbprd(uint16_t ch, uint16_t v)
{
    switch (ch)
    {
${setTbprd}
        default: break;
    }
}

static void EPWM_apiWriteCmpa(uint16_t ch, uint16_t v)
{
    switch (ch)
    {
${setCmpa}
        default: break;
    }
}

static void EPWM_apiWriteTbphs(uint16_t ch, uint16_t v)
{
    switch (ch)
    {
${setTbphs}
        default: break;
    }
}

static void EPWM_apiWritePhsdir(uint16_t ch, uint16_t v)
{
    switch (ch)
    {
${setPhsdir}
        default: break;
    }
}

static uint16_t EPWM_apiReadTbprd(uint16_t ch)
{
    uint16_t tbprd = 0U;
    switch (ch)
    {
${readTbprd}
        default: break;
    }
    return tbprd;
}

/* ------------------------------------------------------------------ */
/* ${t('对外接口', 'public API')} */
/* ------------------------------------------------------------------ */

static int EPWM_apiValid(unsigned int ch)
{
    return (ch >= 1U) && (ch <= EPWM_API_CH_COUNT);
}

void EPWM_setFrequency(unsigned int ch, float fswKhz)
{
    EPWM_API_Param *p;
    uint16_t tbprd;
    uint16_t cmpa;
    uint16_t phsdir = 0U;

    if (!EPWM_apiValid(ch)) { return; }

    p = &g_param[ch - 1U];
    tbprd = EPWM_apiTbprdFromFsw(fswKhz);

    p->fswKhz = fswKhz;
    p->tbprd  = tbprd;

    /* ${t('先改周期，再按“占空比不变”重算比较值；两者都在影子寄存器里，同时生效', 'period first, then re-derive CMPA so duty stays the same; both are shadowed and apply together')} */
    cmpa = EPWM_apiCmpaFromDuty(p->dutyPct, tbprd);
    EPWM_apiWriteTbprd((uint16_t)ch, tbprd);
    EPWM_apiWriteCmpa((uint16_t)ch, cmpa);
    g_lastCmpa[ch - 1U] = cmpa;

    if (p->syncEn != 0U)
    {
        EPWM_apiWriteTbphs((uint16_t)ch, EPWM_apiTbphsFromDeg(p->phaseDeg, tbprd, &phsdir));
        EPWM_apiWritePhsdir((uint16_t)ch, phsdir);
    }
}

void EPWM_setDuty(unsigned int ch, float dutyPct)
{
    EPWM_API_Param *p;
    uint16_t tbprd;
    uint16_t cmpa;

    if (!EPWM_apiValid(ch)) { return; }

    p = &g_param[ch - 1U];
    tbprd = p->tbprd;
    if (tbprd == 0U) { tbprd = EPWM_apiReadTbprd((uint16_t)ch); p->tbprd = tbprd; }

    if (dutyPct < EPWM_API_DUTY_MIN) { dutyPct = EPWM_API_DUTY_MIN; }
    if (dutyPct > EPWM_API_DUTY_MAX) { dutyPct = EPWM_API_DUTY_MAX; }

    p->dutyPct = dutyPct;
    cmpa = EPWM_apiCmpaFromDuty(dutyPct, tbprd);
    EPWM_apiWriteCmpa((uint16_t)ch, cmpa);
    g_lastCmpa[ch - 1U] = cmpa;
}

void EPWM_setPhase(unsigned int ch, float phaseDeg)
{
    EPWM_API_Param *p;
    uint16_t phsdir = 0U;

    if (!EPWM_apiValid(ch)) { return; }

    p = &g_param[ch - 1U];
    if (p->syncEn == 0U) { return; }   /* ${t('未参与同步的通道没有相位可调', 'channels not phase-synced have no phase to set')} */

    p->phaseDeg = phaseDeg;
    EPWM_apiWriteTbphs((uint16_t)ch, EPWM_apiTbphsFromDeg(phaseDeg, p->tbprd, &phsdir));
    EPWM_apiWritePhsdir((uint16_t)ch, phsdir);
}

void EPWM_setParam(unsigned int ch, const EPWM_API_Param *p)
{
    if (!EPWM_apiValid(ch) || (p == 0)) { return; }

    EPWM_setFrequency(ch, p->fswKhz);
    EPWM_setDuty(ch, p->dutyPct);
    EPWM_setPhase(ch, p->phaseDeg);
}

const EPWM_API_Param *EPWM_getParam(unsigned int ch)
{
    if (!EPWM_apiValid(ch)) { return 0; }
    return &g_param[ch - 1U];
}

float EPWM_actualFswKhz(unsigned int ch)
{
    uint16_t tbprd;

    if (!EPWM_apiValid(ch)) { return 0.0f; }
    tbprd = g_param[ch - 1U].tbprd;
    if (tbprd == 0U) { return 0.0f; }

#if EPWM_API_UP_DOWN
    return (EPWM_API_TBCLK_HZ / (float)EPWM_API_TOTAL_DIV) / (2.0f * (float)tbprd) / 1000.0f;
#else
    return (EPWM_API_TBCLK_HZ / (float)EPWM_API_TOTAL_DIV) / ((float)tbprd + 1.0f) / 1000.0f;
#endif
}

uint16_t EPWM_lastCmpa(unsigned int ch)
{
    if (!EPWM_apiValid(ch)) { return 0U; }
    return g_lastCmpa[ch - 1U];
}
`;
}

export function produceRuntimeApi(project: ProjectState, hw: HardwareModel): GeneratedFile[] {
  return [
    { name: 'epwm_api.c', language: 'c', content: sourceFile(project, hw) },
    { name: 'epwm_api.h', language: 'h', content: headerFile(project, hw) },
  ];
}
