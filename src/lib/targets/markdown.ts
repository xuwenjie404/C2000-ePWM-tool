import type { GeneratedFile, ProjectState } from '../../types';
import { countIssues } from '../rules';
import { validateProject } from '../validation';
import type { HardwareModel } from '../hardware';

/**
 * Markdown 设计表目标。
 *
 * 存在的意义：平台不该只产出「机器消费的代码」，还要产出「人消费的文档」——
 * 评审、归档、下厂时需要的是一张参数表，而不是两千行 C。
 *
 * 这个目标同时也证明：新增一种输出格式 = 写一个 produce() + 注册一次。
 */
export function produceMarkdown(project: ProjectState, hw: HardwareModel): GeneratedFile[] {
  const tb = hw.master.tb;
  const issues = validateProject(project, hw);
  const counts = countIssues(issues);
  const isCN = project.commentLang === 'CN';
  const lines: string[] = [];

  const p = (cn: string, en: string) => (isCN ? cn : en);

  lines.push(`# ${p('ePWM 配置表', 'ePWM Configuration Sheet')} — ${hw.device.name}`);
  lines.push('');
  lines.push(
    `> ${p('由 C2000 ePWM Tool 生成；用于设计评审与归档，参数变更请回到工具中修改。', 'Generated by C2000 ePWM Tool; edit in the tool, not here.')}`,
  );
  lines.push('');

  lines.push(`## 1. ${p('工程概览', 'Project overview')}`);
  lines.push('');
  lines.push(`| ${p('项目', 'Item')} | ${p('值', 'Value')} |`);
  lines.push('| --- | --- |');
  lines.push(`| ${p('器件', 'Device')} | ${hw.device.name} (${hw.device.package}) |`);
  lines.push(`| ${p('拓扑', 'Topology')} | ${project.phaseSystem} / ${project.subTopology} |`);
  lines.push(`| ${p('计数模式', 'Count mode')} | ${project.countMode} |`);
  lines.push(`| ${p('目标频率', 'Target f_sw')} | ${project.freqKhz} kHz |`);
  lines.push(`| ${p('实际频率', 'Actual f_sw')} | ${tb.actualFswKhz.toFixed(3)} kHz |`);
  lines.push(`| ${p('开关周期', 'Period')} | ${tb.periodNs.toFixed(0)} ns |`);
  lines.push(`| TBCLK / ${p('分频', 'divider')} | ${hw.device.tbclkMHz} MHz / ${tb.clkDiv}×${tb.hspClkDiv} |`);
  lines.push(`| TBPRD | ${tb.tbprd} |`);
  lines.push(`| ${p('占空比分辨率', 'Duty LSB')} | ${tb.dutyLsbPct.toFixed(3)} % |`);
  lines.push(`| ${p('调制策略', 'Modulation')} | ${project.modulationMode} (M = ${project.modIndex}) |`);
  lines.push(
    `| ${p('保护', 'Protection')} | ${project.tripZone.enabled ? `Trip-Zone ${project.tripZone.action} (${project.tripZone.sources.join('/')})` : p('未启用', 'disabled')} |`,
  );
  lines.push('');

  lines.push(`## 2. ${p('通道寄存器', 'Channel registers')}`);
  lines.push('');
  lines.push(
    `| ePWM | ${p('名称', 'Name')} | ${p('频率', 'f_sw')} (kHz) | TBPRD | CMPA | TBPHS | PHSDIR | DBRED | DBFED | ${p('死区模式', 'DB mode')} | ${p('设置占空比', 'Set duty')} | ${p('实际占空比', 'Actual duty')} |`,
  );
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const ch of hw.channels) {
    if (!ch.cfg.enabled) continue;
    lines.push(
      `| ${ch.cfg.id} | ${ch.cfg.name} | ${ch.tb.actualFswKhz.toFixed(3)} | ${ch.tb.tbprd} | ${ch.cmpA} | ${
        ch.syncEnabled ? ch.phase.tbphs : 0
      } | ${ch.syncEnabled ? ch.phase.phsDir : '-'} | ${ch.dbRed} | ${ch.dbFed} | ${ch.mode.short} | ${ch.cfg.duty.toFixed(
        1,
      )}% | ${ch.wave.actualDutyAPct.toFixed(2)}% |`,
    );
  }
  lines.push('');

  lines.push(`## 3. ${p('死区时间', 'Dead-band timing')}`);
  lines.push('');
  lines.push(
    `| ePWM | RED (ns) | FED (ns) | ${p('A 开通前死区', 'before A on')} | ${p('B 开通前死区', 'before B on')} | ${p('脉宽被吞', 'pulse swallowed')} |`,
  );
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const ch of hw.channels) {
    if (!ch.cfg.enabled) continue;
    const swallowed =
      ch.wave.swallowedA || ch.wave.swallowedB
        ? [ch.wave.swallowedA ? 'A' : '', ch.wave.swallowedB ? 'B' : ''].filter(Boolean).join(' + ')
        : p('否', 'no');
    lines.push(
      `| ${ch.cfg.id} | ${(ch.dbRed * ch.tb.stepNs).toFixed(0)} | ${(ch.dbFed * ch.tb.stepNs).toFixed(0)} | ${ch.wave.deadTimeRiseNs.toFixed(
        0,
      )} | ${ch.wave.deadTimeFallNs.toFixed(0)} | ${swallowed} |`,
    );
  }
  lines.push('');

  lines.push(`## 4. ${p('引脚分配', 'Pin assignment')}`);
  lines.push('');
  lines.push(`| ${p('信号', 'Signal')} | GPIO | ${p('引脚号', 'Pin')} | ${p('复用寄存器', 'Mux register')} |`);
  lines.push('| --- | --- | --- | --- |');
  for (const ch of hw.channels) {
    if (!ch.cfg.enabled) continue;
    (['A', 'B'] as const).forEach(sub => {
      const opt = sub === 'A' ? ch.muxA : ch.muxB;
      if (!opt) return;
      lines.push(`| ePWM${ch.cfg.id}${sub} | ${opt.gpio} | #${opt.pin} | ${opt.reg}.${opt.gpio} = ${opt.mux} |`);
    });
  }
  lines.push('');

  lines.push(`## 5. ${p('设计校验', 'Design checks')}`);
  lines.push('');
  if (issues.length === 0) {
    lines.push(`✅ ${p('未发现问题。', 'No issues found.')}`);
  } else {
    lines.push(
      `${p('错误', 'Errors')}: **${counts.error}** · ${p('警告', 'Warnings')}: **${counts.warn}** · ${p('提示', 'Info')}: **${counts.info}**`,
    );
    lines.push('');
    for (const issue of issues) {
      const tag = issue.severity === 'error' ? '❌' : issue.severity === 'warn' ? '⚠️' : 'ℹ️';
      lines.push(`- ${tag} **${issue.title}** — ${issue.detail}`);
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(
    `*${p('本表由工具自动生成，上电前请用示波器复核死区与最小脉宽。', 'Auto-generated. Verify dead-band and minimum pulse width on hardware before power-up.')}*`,
  );

  return [{ name: 'epwm_config.md', language: 'md', content: lines.join('\n') }];
}
