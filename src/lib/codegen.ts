const U = (v: number): string => `${Math.round(v)}U`;

/** 生成注释（跟随 CN / EN 语言开关） */
function makeCommenter(isCN: boolean) {
  return (cn: string, en: string): string => (isCN ? cn : en);
}

/**
 * 动作限定子模块的 AQ 配置。
 *   增减计数：CAU=CLEAR / CAD=SET  -> duty = CMPA / TBPRD
 *   单向计数：ZRO=SET / CAU=CLEAR  -> duty = CMPA / (TBPRD + 1)
 * 单向计数下若沿用 CAU=CLEAR / CAD=SET，CAD 事件永不发生，输出会恒为低电平，
 * 这是原版工具生成代码里的隐性错误。
 */
function aqConfig(countMode: 'UP_DOWN' | 'UP'): { ca: string; cau: string; cad: string } {
  if (countMode === 'UP_DOWN') return { ca: 'AQ_CLEAR', cau: 'AQ_CLEAR', cad: 'AQ_SET' };
  return { ca: 'AQ_SET', cau: 'AQ_CLEAR', cad: 'AQ_NO_ACTION' };
}

function tripActionBitfield(action: string): string {
  switch (action) {
    case 'FORCE_HIGH':
      return 'TZ_FORCE_HI';
    case 'HI_Z':
      return 'TZ_HIZ';
    case 'DO_NOTHING':
      return 'TZ_DO_NOTHING';
    default:
      return 'TZ_FORCE_LO';
  }
}

function tripActionDriver(action: string): string {
  switch (action) {
    case 'FORCE_HIGH':
      return 'EPWM_TZ_ACTION_HIGH';
    case 'HI_Z':
      return 'EPWM_TZ_ACTION_HIGH_Z';
    case 'DO_NOTHING':
      return 'EPWM_TZ_ACTION_DISABLE';
    default:
      return 'EPWM_TZ_ACTION_LOW';
  }
}

function fileHeader(project: ProjectState, hw: HardwareModel, fileName: string, isCN: boolean): string {
  const t = makeCommenter(isCN);
  const style = project.codeTarget === 'BITFIELD' ? 'Bit-Field' : 'DriverLib';
  return `/**
 * @file    ${fileName}
 * @brief   ${t('TI C2000 ePWM 初始化代码', 'TI C2000 ePWM initialization code')}
 *
 * ${t('由 C2000 ePWM Tool 自动生成', 'Generated by C2000 ePWM Tool')}
 *   ${t('器件', 'Device')}     : ${hw.device.name} (${hw.device.package})
 *   ${t('代码风格', 'Style')}    : ${style}
 *   ${t('时基', 'Time base')}    : TBCLK ${hw.device.tbclkMHz} MHz, f_sw ${hw.master.tb.actualFswKhz.toFixed(3)} kHz
 *   ${t('计数模式', 'Count mode')} : ${project.countMode === 'UP_DOWN' ? 'TB_COUNT_UPDOWN' : 'TB_COUNT_UP'}
 *
 * ${t('注意：上电前请人工复核寄存器值与引脚复用。', 'Review register values and pin mux before powering up.')}
 * ${t('不同器件/封装的位域名可能略有差异，以对应 TRM 与头文件为准。', 'Bit-field names vary slightly between devices; trust your TRM and headers.')}
 */
`;
}

/* ------------------------------------------------------------------ *
 * Bit-Field 风格：单通道
 * ------------------------------------------------------------------ */
function bitfieldChannel(c: ResolvedChannel, project: ProjectState, hw: HardwareModel): string {
  const isCN = project.commentLang === 'CN';
  const t = makeCommenter(isCN);
  const n = c.cfg.id;
  const aq = aqConfig(project.countMode);
  const clk = findClkDiv(c.tb.clkDiv);
  const hsp = findHspClkDiv(c.tb.hspClkDiv);
  const L: string[] = [];

  L.push(`// ============================================================================`);
  L.push(
    `// ${t(`ePWM${n} - ${c.cfg.name}`, `ePWM${n} - ${c.cfg.name}`)} | ${t('开关频率', 'f_sw')} ${c.tb.actualFswKhz.toFixed(3)} kHz | ${t(
      '死区',
      'dead-band',
    )} RED=${(c.dbRed * c.tb.stepNs).toFixed(0)} ns / FED=${(c.dbFed * c.tb.stepNs).toFixed(0)} ns`,
  );
  L.push(`// ============================================================================`);
  L.push(`void EPWM_initCh${n}(void)`);
  L.push(`{`);
  L.push(`    EALLOW;`);
  L.push(``);
  L.push(`    // ---- 1. ${t('时基子模块 Time-Base', 'Time-Base Submodule')} ----`);
  L.push(`    EPwm${n}Regs.TBPRD = ${U(c.tb.tbprd)};   // ${t('开关周期', 'period')} ${c.tb.periodNs.toFixed(0)} ns`);
  L.push(`    EPwm${n}Regs.TBPHS.bit.TBPHS = ${U(c.syncEnabled ? c.phase.tbphs : 0)};`);
  if (c.syncEnabled) {
    L.push(`    EPwm${n}Regs.TBCTL.bit.PHSEN = TB_ENABLE;`);
    L.push(`    EPwm${n}Regs.TBCTL.bit.PHSDIR = ${c.phase.phsDir === 'UP' ? 'TB_UP' : 'TB_DOWN'};`);
    L.push(
      `    EPwm${n}Regs.TBCTL.bit.SYNCOSEL = TB_SYNC_IN;   // ${t('从模块：同步脉冲继续下传', 'slave: pass sync downstream')}`,
    );
  } else {
    L.push(`    EPwm${n}Regs.TBCTL.bit.PHSEN = TB_DISABLE;`);
    L.push(
      n === 1
        ? `    EPwm${n}Regs.TBCTL.bit.SYNCOSEL = TB_CTR_ZERO;   // ${t('主模块：CTR=0 时发出同步', 'master: emit sync at CTR=0')}`
        : `    EPwm${n}Regs.TBCTL.bit.SYNCOSEL = TB_SYNC_DISABLE;`,
    );
  }
  L.push(
    `    EPwm${n}Regs.TBCTL.bit.CTRMODE = ${project.countMode === 'UP_DOWN' ? 'TB_COUNT_UPDOWN' : 'TB_COUNT_UP'};`,
  );
  L.push(`    EPwm${n}Regs.TBCTL.bit.PRDLD = TB_SHADOW;`);
  L.push(`    EPwm${n}Regs.TBCTL.bit.CLKDIV = ${clk.bitEnum};`);
  L.push(`    EPwm${n}Regs.TBCTL.bit.HSPCLKDIV = ${hsp.bitEnum};`);
  L.push(`    EPwm${n}Regs.TBCTR = 0x0000U;`);
  L.push(``);
  L.push(`    // ---- 2. ${t('计数比较与动作限定', 'Counter-Compare and Action Qualifier')} ----`);
  L.push(`    EPwm${n}Regs.CMPCTL.bit.SHDWAMODE = CC_SHADOW;`);
  L.push(
    `    EPwm${n}Regs.CMPCTL.bit.LOADAMODE = CC_CTR_ZERO;   // ${t('在 CTR=0 安全装载 CMPA', 'load CMPA at CTR=0')}`,
  );
  L.push(`    EPwm${n}Regs.CMPA.bit.CMPA = ${U(c.cmpA)};          // ${t('占空比', 'duty')} ${c.cfg.duty.toFixed(1)}%`);
  if (c.mode.bypass) {
    L.push(`    EPwm${n}Regs.CMPCTL.bit.SHDWBMODE = CC_SHADOW;`);
    L.push(`    EPwm${n}Regs.CMPCTL.bit.LOADBMODE = CC_CTR_ZERO;`);
    L.push(
      `    EPwm${n}Regs.CMPB.bit.CMPB = ${U(c.cmpB)};          // ${t('B 相占空比', 'B-phase duty')} ${c.cfg.dutyB.toFixed(1)}%`,
    );
  }
  if (project.countMode === 'UP_DOWN') {
    L.push(`    EPwm${n}Regs.AQCTLA.bit.ZRO = AQ_NO_ACTION;`);
    L.push(
      `    EPwm${n}Regs.AQCTLA.bit.CAU = ${aq.cau};            // ${t('上行等于 CMPA -> 拉低', 'up-count match CMPA -> low')}`,
    );
    L.push(
      `    EPwm${n}Regs.AQCTLA.bit.CAD = ${aq.cad};            // ${t('下行等于 CMPA -> 拉高', 'down-count match CMPA -> high')}`,
    );
    L.push(`    EPwm${n}Regs.AQCTLA.bit.PRD = AQ_NO_ACTION;`);
  } else {
    L.push(`    EPwm${n}Regs.AQCTLA.bit.ZRO = ${aq.ca};            // ${t('CTR=0 -> 拉高', 'CTR=0 -> high')}`);
    L.push(
      `    EPwm${n}Regs.AQCTLA.bit.CAU = ${aq.cau};            // ${t('上行等于 CMPA -> 拉低', 'up-count match CMPA -> low')}`,
    );
    L.push(`    EPwm${n}Regs.AQCTLA.bit.CAD = AQ_NO_ACTION;`);
    L.push(`    EPwm${n}Regs.AQCTLA.bit.PRD = AQ_NO_ACTION;`);
  }
  if (c.mode.bypass) {
    L.push(
      `    // ${t('BYPASS：B 相必须由 AQCTLB 独立驱动，否则 OUTB 不随比较值变化', 'BYPASS: OUTB needs its own AQCTLB setup, otherwise it never changes')}`,
    );
    if (project.countMode === 'UP_DOWN') {
      L.push(`    EPwm${n}Regs.AQCTLB.bit.CAU = AQ_CLEAR;`);
      L.push(`    EPwm${n}Regs.AQCTLB.bit.CAD = AQ_SET;`);
    } else {
      L.push(`    EPwm${n}Regs.AQCTLB.bit.ZRO = AQ_SET;`);
      L.push(`    EPwm${n}Regs.AQCTLB.bit.CAU = AQ_CLEAR;`);
    }
  }
  L.push(``);
  L.push(`    // ---- 3. ${t('死区子模块 Dead-Band', 'Dead-Band Submodule')} ----`);
  if (c.mode.bypass) {
    L.push(
      `    EPwm${n}Regs.DBCTL.bit.OUT_MODE = DB_DISABLE;   // ${t('旁路：OUTA/OUTB 直接来自 AQ', 'bypass: OUTA/OUTB from AQ')}`,
    );
    L.push(`    EPwm${n}Regs.DBCTL.bit.IN_MODE = DBA_ALL;`);
    L.push(`    EPwm${n}Regs.DBRED.bit.DBRED = 0U;`);
    L.push(`    EPwm${n}Regs.DBFED.bit.DBFED = 0U;`);
  } else {
    L.push(`    EPwm${n}Regs.DBCTL.bit.IN_MODE  = ${c.inMode.id};`);
    L.push(
      `    EPwm${n}Regs.DBCTL.bit.POLSEL   = ${c.mode.polselBitfield};   // ${c.mode.short} = 0x${c.mode.polsel
        .toString(16)
        .toUpperCase()}`,
    );
    L.push(`    EPwm${n}Regs.DBCTL.bit.OUT_MODE = DB_FULL_ENABLE;`);
    L.push(`    EPwm${n}Regs.DBRED.bit.DBRED = ${U(c.dbRed)};   // ${(c.dbRed * c.tb.stepNs).toFixed(1)} ns`);
    L.push(`    EPwm${n}Regs.DBFED.bit.DBFED = ${U(c.dbFed)};   // ${(c.dbFed * c.tb.stepNs).toFixed(1)} ns`);
  }
  L.push(``);

  if (c.cfg.hrpwm && hw.device.hasHRPWM) {
    L.push(`    // ---- 4. HRPWM ${t('高分辨率微边沿', 'high-resolution MEP')} ----`);
    L.push(`    EPwm${n}Regs.HRCNFG.all = 0x0;`);
    L.push(`    EPwm${n}Regs.HRCNFG.bit.EDGMODE = HR_BOTH;`);
    L.push(`    EPwm${n}Regs.HRCNFG.bit.CTLMODE = HR_CAL;`);
    L.push(`    EPwm${n}Regs.HRCNFG.bit.HRLOAD  = HR_CTR_ZERO;`);
    L.push(
      `    EPwm${n}Regs.HRCNFG.bit.AUTOCONV = 1;   // ${t('自动把 CMPAHR 并入比较值', 'auto-apply CMPAHR')}`,
    );
    L.push(`    // ${t('CMPAHR 补偿量 (Q8)', 'CMPAHR offset (Q8)')} = 0x${c.hrpwm.cmpahr.toString(16).toUpperCase()}`);
    L.push(
      `    // ${t('Type-0 器件还需周期调用 SFO() 完成 MEP 校准', 'Type-0 devices also need periodic SFO() calibration')}`,
    );
    L.push(``);
  }

  if (project.tripZone.enabled) {
    L.push(`    // ---- 5. Trip-Zone ${t('硬件故障保护', 'fault protection')} ----`);
    L.push(
      `    // TZCTL ${t('编码：0=不动作 1=强制高 2=强制低 3=高阻', 'encoding: 0=none 1=force high 2=force low 3=hi-Z')}`,
    );
    for (const src of project.tripZone.sources) {
      const idx = src.replace('TZ', '');
      const field = project.tripZone.action === 'OST' ? `OSHT${idx}` : `CBC${idx}`;
      L.push(`    EPwm${n}Regs.TZSEL.bit.${field} = 1;`);
    }
    L.push(`    EPwm${n}Regs.TZCTL.bit.TZA = ${tripActionBitfield(project.tripZone.outA)};`);
    L.push(`    EPwm${n}Regs.TZCTL.bit.TZB = ${tripActionBitfield(project.tripZone.outB)};`);
    if (project.tripZone.interrupt) {
      L.push(`    EPwm${n}Regs.TZEINT.bit.${project.tripZone.action === 'OST' ? 'OST' : 'CBC'} = 1;`);
    }
    L.push(``);
  }

  if (project.adcTrigger.enabled) {
    const sel =
      project.adcTrigger.source === 'CTR_PRD'
        ? 'ET_CTR_PRD'
        : project.adcTrigger.source === 'CTR_ZERO_OR_PRD'
          ? 'ET_CTR_ZERO_PRD'
          : 'ET_CTR_ZERO';
    const pre = ['ET_1ST', 'ET_2ND', 'ET_3RD', 'ET_4TH', 'ET_5TH', 'ET_6TH', 'ET_7TH', 'ET_8TH'][
      Math.min(7, Math.max(0, project.adcTrigger.prescale - 1))
    ];
    L.push(`    // ---- ${t('事件触发：启动 ADC 采样', 'Event-Trigger: start ADC conversion')} ----`);
    L.push(`    EPwm${n}Regs.ETSEL.bit.SOCAEN  = 1;`);
    L.push(`    EPwm${n}Regs.ETSEL.bit.SOCASEL = ${sel};`);
    L.push(`    EPwm${n}Regs.ETPS.bit.SOCAPRD   = ${pre};`);
    L.push(``);
  }

  L.push(`    EDIS;`);
  L.push(`}`);
  return L.join('\n');
}

/* ------------------------------------------------------------------ *
 * DriverLib 风格：单通道
 * ------------------------------------------------------------------ */
function driverlibChannel(c: ResolvedChannel, project: ProjectState, hw: HardwareModel): string {
  const t = makeCommenter(project.commentLang === 'CN');
  const n = c.cfg.id;
  const clk = findClkDiv(c.tb.clkDiv);
  const hsp = findHspClkDiv(c.tb.hspClkDiv);
  // DBCTL 位布局：IN_MODE[1:0] / POLSEL[3:2] / OUT_MODE[5:4]，FULL_ENABLE = 0x3
  const dbctl = (c.inMode.code & 0x3) | ((c.mode.polsel & 0x3) << 2) | (0x3 << 4);
  const L: string[] = [];

  L.push(`// ${t(`ePWM${n} - ${c.cfg.name}`, `ePWM${n} - ${c.cfg.name}`)}`);
  L.push(`void EPWM_initCh${n}(void)`);
  L.push(`{`);
  L.push(`    EPWM_setTimeBasePeriod(EPWM${n}_BASE, ${U(c.tb.tbprd)});`);
  L.push(`    EPWM_setTimeBaseCounter(EPWM${n}_BASE, 0U);`);
  L.push(
    `    EPWM_setTimeBaseCounterMode(EPWM${n}_BASE, ${
      project.countMode === 'UP_DOWN' ? 'EPWM_COUNTER_MODE_UP_DOWN' : 'EPWM_COUNTER_MODE_UP'
    });`,
  );
  L.push(`    EPWM_setClockPrescaler(EPWM${n}_BASE, ${clk.driverEnum}, ${hsp.driverEnum});`);
  L.push(`    EPWM_setPeriodLoadMode(EPWM${n}_BASE, EPWM_PERIOD_SHADOW_LOAD);`);

  if (c.syncEnabled) {
    L.push(`    EPWM_setPhaseShift(EPWM${n}_BASE, ${U(c.phase.tbphs)});`);
    L.push(`    EPWM_enablePhaseShiftLoad(EPWM${n}_BASE);`);
    L.push(
      `    EPWM_setCountModeAfterSync(EPWM${n}_BASE, ${
        c.phase.phsDir === 'UP' ? 'EPWM_COUNT_MODE_UP_AFTER_SYNC' : 'EPWM_COUNT_MODE_DOWN_AFTER_SYNC'
      });`,
    );
    L.push(`    EPWM_enableSyncOutPulseSource(EPWM${n}_BASE, EPWM_SYNC_OUT_PULSE_ON_SOFTWARE);`);
  } else {
    L.push(`    EPWM_disablePhaseShiftLoad(EPWM${n}_BASE);`);
    L.push(
      `    EPWM_enableSyncOutPulseSource(EPWM${n}_BASE, ${
        n === 1 ? 'EPWM_SYNC_OUT_PULSE_ON_CNTR_ZERO' : 'EPWM_SYNC_OUT_PULSE_ON_SOFTWARE'
      });`,
    );
  }

  L.push(
    `    EPWM_setCounterCompareShadowLoadMode(EPWM${n}_BASE, EPWM_COUNTER_COMPARE_A, EPWM_COMP_LOAD_ON_CNTR_ZERO);`,
  );
  L.push(`    EPWM_setCounterCompareValue(EPWM${n}_BASE, EPWM_COUNTER_COMPARE_A, ${U(c.cmpA)});`);

  if (project.countMode === 'UP_DOWN') {
    L.push(
      `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_LOW, EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPA);`,
    );
    L.push(
      `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_HIGH, EPWM_AQ_OUTPUT_ON_TIMEBASE_DOWN_CMPA);`,
    );
  } else {
    L.push(
      `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_HIGH, EPWM_AQ_OUTPUT_ON_TIMEBASE_ZERO);`,
    );
    L.push(
      `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_LOW, EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPA);`,
    );
  }

  if (c.mode.bypass) {
    L.push(
      `    EPWM_setCounterCompareShadowLoadMode(EPWM${n}_BASE, EPWM_COUNTER_COMPARE_B, EPWM_COMP_LOAD_ON_CNTR_ZERO);`,
    );
    L.push(`    EPWM_setCounterCompareValue(EPWM${n}_BASE, EPWM_COUNTER_COMPARE_B, ${U(c.cmpB)});`);
    if (project.countMode === 'UP_DOWN') {
      L.push(
        `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_B, EPWM_AQ_OUTPUT_LOW, EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPB);`,
      );
      L.push(
        `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_B, EPWM_AQ_OUTPUT_HIGH, EPWM_AQ_OUTPUT_ON_TIMEBASE_DOWN_CMPB);`,
      );
    } else {
      L.push(
        `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_B, EPWM_AQ_OUTPUT_HIGH, EPWM_AQ_OUTPUT_ON_TIMEBASE_ZERO);`,
      );
      L.push(
        `    EPWM_setActionQualifierAction(EPWM${n}_BASE, EPWM_AQ_OUTPUT_B, EPWM_AQ_OUTPUT_LOW, EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPB);`,
      );
    }
    L.push(`    // ${t('旁路死区：OUTA/OUTB 完全由 AQ 决定', 'dead-band bypassed: OUTA/OUTB driven by AQ')}`);
    L.push(`    HWREGH(EPWM${n}_BASE + EPWM_O_DBCTL) = 0x0000U;`);
  } else {
    L.push(`    EPWM_setRisingEdgeDelayCount(EPWM${n}_BASE, ${U(c.dbRed)});`);
    L.push(`    EPWM_setFallingEdgeDelayCount(EPWM${n}_BASE, ${U(c.dbFed)});`);
    L.push(
      `    // DBCTL = 0x${dbctl
        .toString(16)
        .toUpperCase()
        .padStart(4, '0')}：OUT_MODE=FULL(0x3)<<4 | POLSEL=${c.mode.short}(0x${c.mode.polsel.toString(16)})<<2 | IN_MODE=${
        c.inMode.id
      }(0x${c.inMode.code.toString(16)})`,
    );
    L.push(`    HWREGH(EPWM${n}_BASE + EPWM_O_DBCTL) = 0x${dbctl.toString(16).toUpperCase().padStart(4, '0')}U;`);
  }

  if (c.cfg.hrpwm && hw.device.hasHRPWM) {
    L.push(`    // HRPWM ${t('高分辨率', 'high resolution')}: ${hw.device.mepStepPs} ps MEP`);
    L.push(`    EPWM_setEmulationMode(EPWM${n}_BASE, EPWM_EMULATION_FREE_RUN);`);
    L.push(`    HWREGH(EPWM${n}_BASE + EPWM_O_HRCNFG) = 0x0003U;   // EDGMODE=BOTH, CTLMODE=CAL, HRLOAD=CTR_ZERO`);
    L.push(`    // ${t('CMPAHR 补偿量', 'CMPAHR offset')} = 0x${c.hrpwm.cmpahr.toString(16).toUpperCase()}`);
  }

  if (project.tripZone.enabled) {
    for (const src of project.tripZone.sources) {
      const idx = src.replace('TZ', '');
      const sig =
        project.tripZone.action === 'OST' ? `EPWM_TZ_SIGNAL_OSHT${idx}` : `EPWM_TZ_SIGNAL_CBC${idx}`;
      L.push(`    EPWM_enableTripZoneSignals(EPWM${n}_BASE, ${sig});`);
    }
    L.push(
      `    EPWM_setTripZoneAction(EPWM${n}_BASE, EPWM_TZ_ACTION_EVENT_TZA, ${tripActionDriver(project.tripZone.outA)});`,
    );
    L.push(
      `    EPWM_setTripZoneAction(EPWM${n}_BASE, EPWM_TZ_ACTION_EVENT_TZB, ${tripActionDriver(project.tripZone.outB)});`,
    );
    if (project.tripZone.interrupt) {
      L.push(
        `    EPWM_enableTripZoneInterrupt(EPWM${n}_BASE, ${
          project.tripZone.action === 'OST' ? 'EPWM_TZ_INTERRUPT_OST' : 'EPWM_TZ_INTERRUPT_CBC'
        });`,
      );
    }
  }

  if (project.adcTrigger.enabled) {
    const sel =
      project.adcTrigger.source === 'CTR_PRD'
        ? 'EPWM_SOC_TBCTR_PERIOD'
        : project.adcTrigger.source === 'CTR_ZERO_OR_PRD'
          ? 'EPWM_SOC_TBCTR_ZERO_OR_PERIOD'
          : 'EPWM_SOC_TBCTR_ZERO';
    L.push(`    EPWM_enableADCTrigger(EPWM${n}_BASE, EPWM_SOC_A);`);
    L.push(`    EPWM_setADCTriggerSource(EPWM${n}_BASE, EPWM_SOC_A, ${sel});`);
    L.push(`    EPWM_setADCTriggerEventPrescale(EPWM${n}_BASE, EPWM_SOC_A, ${U(project.adcTrigger.prescale)});`);
  }

  L.push(`}`);
  return L.join('\n');
}

function gpioInit(hw: HardwareModel, project: ProjectState): string {
  const t = makeCommenter(project.commentLang === 'CN');
  const L: string[] = [];
  L.push(`void EPWM_initGpio(void)`);
  L.push(`{`);
  if (project.codeTarget === 'BITFIELD') {
    L.push(`    EALLOW;`);
    for (const c of hw.channels) {
      if (!c.cfg.enabled) continue;
      for (const sub of ['A', 'B'] as const) {
        const opt = sub === 'A' ? c.muxA : c.muxB;
        if (!opt) continue;
        L.push(
          `    GpioCtrlRegs.${opt.reg}.bit.${opt.gpio} = ${opt.mux};   // ePWM${c.cfg.id}${sub} -> ${opt.gpio} (Pin #${opt.pin})`,
        );
      }
    }
    L.push(`    EDIS;`);
  } else {
    for (const c of hw.channels) {
      if (!c.cfg.enabled) continue;
      for (const sub of ['A', 'B'] as const) {
        const opt = sub === 'A' ? c.muxA : c.muxB;
        if (!opt) continue;
        const gpioNum = opt.gpio.replace('GPIO', '');
        L.push(
          `    GPIO_setPinConfig(GPIO_${gpioNum}_EPWM${c.cfg.id}${sub});   // ${opt.gpio} (Pin #${opt.pin}), mux ${opt.mux}`,
        );
      }
    }
  }
  L.push(
    `    // ${t(
      '注：若上面的复用宏在 pin_map.h 中不存在，请退回 Bit-Field 写法',
      'Note: if a pin-map macro is missing in pin_map.h, fall back to the bit-field form',
    )}`,
  );
  L.push(`}`);
  return L.join('\n');
}

/* ------------------------------------------------------------------ *
 * 调制 ISR
 * ------------------------------------------------------------------ */
function isrBlock(hw: HardwareModel, project: ProjectState): string {
  if (project.modulationMode === 'FIXED') return '';
  const t = makeCommenter(project.commentLang === 'CN');
  const info = modulationSamplingInfo(project.freqKhz, project.fundFreqHz, project.countMode);
  const span = project.countMode === 'UP_DOWN' ? hw.master.tb.tbprd : hw.master.tb.tbprd + 1;
  const halfSpan = Math.floor(span / 2);
  const enabled = hw.channels.filter(c => c.cfg.enabled);
  const isBitfield = project.codeTarget === 'BITFIELD';
  const L: string[] = [];

  const writeCmp = (id: number, expr: string): string =>
    isBitfield
      ? `    EPwm${id}Regs.CMPA.bit.CMPA = ${expr};`
      : `    EPWM_setCounterCompareValue(EPWM${id}_BASE, EPWM_COUNTER_COMPARE_A, ${expr});`;

  L.push(`// ============================================================================`);
  L.push(
    `// ${t(
      `${project.modulationMode} 实时调制中断：每个开关周期更新一次占空比`,
      `${project.modulationMode} real-time modulation ISR: duty updated once per switching period`,
    )}`,
  );
  L.push(
    `//   ${t('基波频率', 'fundamental')} ${project.fundFreqHz} Hz | ${t('调制比', 'mod index')} ${project.modIndex} | ${t(
      '每周期采样点',
      'samples/cycle',
    )} ${info.samplesPerCycle}`,
  );
  L.push(`// ============================================================================`);
  L.push(`#define EPWM_TOOL_TWO_PI     6.28318530718f`);
  L.push(
    `#define EPWM_TOOL_STEP_RAD   ${info.stepRad.toFixed(9)}f   // 2*pi*${project.fundFreqHz}/${Math.round(info.isrHz)}`,
  );
  L.push(`#define EPWM_TOOL_MOD_IDX    ${project.modIndex.toFixed(6)}f`);
  L.push(`#define EPWM_TOOL_HALF_SPAN  ${halfSpan}U`);
  L.push(`#define EPWM_TOOL_CMP_MAX    ${hw.master.tb.tbprd}U`);
  L.push(``);
  L.push(`volatile float g_thetaRad = 0.0f;`);
  L.push(``);
  L.push(`static inline uint16_t EPWM_toolDutyToCmp(float v)`);
  L.push(`{`);
  L.push(`    // v 属于 [-1, 1]，映射为 CMP = HALF_SPAN * (1 + v)，并夹紧保证最小脉宽`);
  L.push(`    float cmp = (float)EPWM_TOOL_HALF_SPAN * (1.0f + v);`);
  L.push(`    if (cmp < 1.0f) cmp = 1.0f;`);
  L.push(`    if (cmp > (float)(EPWM_TOOL_CMP_MAX - 1U)) cmp = (float)(EPWM_TOOL_CMP_MAX - 1U);`);
  L.push(`    return (uint16_t)cmp;`);
  L.push(`}`);
  L.push(``);
  L.push(`__interrupt void epwm1_isr(void)`);
  L.push(`{`);
  L.push(`    g_thetaRad += EPWM_TOOL_STEP_RAD;`);
  L.push(`    if (g_thetaRad >= EPWM_TOOL_TWO_PI) g_thetaRad -= EPWM_TOOL_TWO_PI;`);
  L.push(``);
  L.push(`    float v_u = EPWM_TOOL_MOD_IDX * sinf(g_thetaRad);`);

  if (project.phaseSystem === '1P') {
    L.push(`    float v_v = -v_u;   // ${t('单相互补桥臂', 'single-phase complementary leg')}`);
    L.push(``);
    if (enabled[0]) L.push(writeCmp(enabled[0].cfg.id, 'EPWM_toolDutyToCmp(v_u)'));
    if (enabled[1]) L.push(writeCmp(enabled[1].cfg.id, 'EPWM_toolDutyToCmp(v_v)'));
  } else {
    L.push(`    float v_v = EPWM_TOOL_MOD_IDX * sinf(g_thetaRad - 2.094395102f);`);
    L.push(`    float v_w = EPWM_TOOL_MOD_IDX * sinf(g_thetaRad + 2.094395102f);`);
    if (project.modulationMode === 'SVPWM') {
      L.push(``);
      L.push(
        `    // ${t(
          'SVPWM 零序注入（最大最小值法）：等效三次谐波注入的马鞍波，母线利用率 +15.47%',
          'SVPWM min-max zero-sequence injection: +15.47% DC-bus utilisation',
        )}`,
      );
      L.push(`    {`);
      L.push(`        float v_max = v_u > v_v ? (v_u > v_w ? v_u : v_w) : (v_v > v_w ? v_v : v_w);`);
      L.push(`        float v_min = v_u < v_v ? (v_u < v_w ? v_u : v_w) : (v_v < v_w ? v_v : v_w);`);
      L.push(`        float v_off = -0.5f * (v_max + v_min);`);
      L.push(`        v_u += v_off;`);
      L.push(`        v_v += v_off;`);
      L.push(`        v_w += v_off;`);
      L.push(`    }`);
    }
    L.push(``);
    L.push(
      `    // ${t('写入 CMPA 影子寄存器，在下一个 CTR=0 时同步生效', 'write CMPA shadow; takes effect at next CTR=0')}`,
    );
    if (enabled[0]) L.push(writeCmp(enabled[0].cfg.id, 'EPWM_toolDutyToCmp(v_u)'));
    if (enabled[1]) L.push(writeCmp(enabled[1].cfg.id, 'EPWM_toolDutyToCmp(v_v)'));
    if (enabled[2]) L.push(writeCmp(enabled[2].cfg.id, 'EPWM_toolDutyToCmp(v_w)'));
  }

  L.push(``);
  L.push(`    ${isBitfield ? 'EPwm1Regs.ETCLR.bit.INT = 1;' : 'EPWM_clearEventTriggerInterruptFlag(EPWM1_BASE);'}`);
  L.push(
    `    ${isBitfield ? 'PieCtrlRegs.PIEACK.all = PIEACK_GROUP3;' : 'Interrupt_clearACKGroup(INTERRUPT_ACK_GROUP3);'}`,
  );
  L.push(`}`);
  return L.join('\n');
}

function mainBlock(hw: HardwareModel, project: ProjectState): string {
  const t = makeCommenter(project.commentLang === 'CN');
  const isBitfield = project.codeTarget === 'BITFIELD';
  const hasMod = project.modulationMode !== 'FIXED';
  const enabled = hw.channels.filter(c => c.cfg.enabled);
  const L: string[] = [];

  L.push(`int main(void)`);
  L.push(`{`);
  if (isBitfield) {
    L.push(`    InitSysCtrl();`);
    L.push(`    DINT;`);
    L.push(`    InitPieCtrl();`);
    L.push(`    IER = 0x0000U;`);
    L.push(`    IFR = 0x0000U;`);
    L.push(`    InitPieVectTable();`);
  } else {
    L.push(`    Device_init();`);
    L.push(`    Device_initGPIO();`);
    L.push(`    Interrupt_initModule();`);
    L.push(`    Interrupt_initVectorTable();`);
  }
  L.push(``);
  L.push(`    EPWM_initGpio();`);
  L.push(``);
  L.push(
    `    // ${t('配置前先关闭全局时基同步，避免装载过程中计数器错位', 'hold TBCLKSYNC low while configuring to keep counters aligned')}`,
  );
  L.push(`    EALLOW;`);
  L.push(`    CpuSysRegs.PCLKCR0.bit.TBCLKSYNC = 0;`);
  L.push(`    EDIS;`);
  L.push(``);
  for (const c of enabled) L.push(`    EPWM_initCh${c.cfg.id}();`);
  L.push(``);
  L.push(`    EALLOW;`);
  L.push(
    `    CpuSysRegs.PCLKCR0.bit.TBCLKSYNC = 1;   // ${t(
      '统一放行：所有模块在同一 TBCLK 边沿启动',
      'release: all modules start on the same edge',
    )}`,
  );
  L.push(`    EDIS;`);

  if (hasMod) {
    L.push(``);
    L.push(`    // ${t('注册 EPWM1 周期中断（调制用）', 'register the EPWM1 period interrupt for modulation')}`);
    L.push(`    EALLOW;`);
    L.push(
      isBitfield ? `    PieVectTable.EPWM1_INT = &epwm1_isr;` : `    Interrupt_register(INT_EPWM1, &epwm1_isr);`,
    );
    L.push(`    EDIS;`);
    L.push(``);
    if (isBitfield) {
      L.push(`    EPwm1Regs.ETSEL.bit.INTSEL = ET_CTR_ZERO;`);
      L.push(`    EPwm1Regs.ETSEL.bit.INTEN  = 1;`);
      L.push(`    EPwm1Regs.ETPS.bit.INTPRD  = ET_1ST;`);
      L.push(`    IER |= M_INT3;`);
      L.push(`    PieCtrlRegs.PIEIER3.bit.INTx1 = 1;`);
      L.push(`    EINT;`);
      L.push(`    ERTM;`);
    } else {
      L.push(`    EPWM_setInterruptSource(EPWM1_BASE, EPWM_INT_TBCTR_ZERO);`);
      L.push(`    EPWM_enableInterrupt(EPWM1_BASE);`);
      L.push(`    EPWM_setInterruptEventCount(EPWM1_BASE, 1U);`);
      L.push(`    Interrupt_enable(INT_EPWM1);`);
      L.push(`    EINT;`);
      L.push(`    ERTM;`);
    }
  }

  L.push(``);
  L.push(`    for (;;)`);
  L.push(`    {`);
  L.push(
    `        // ${t('主循环：可在此加入通信、状态机、软启动等逻辑', 'main loop: add comms / state machine / soft-start here')}`,
  );
  L.push(`        NOP;`);
  L.push(`    }`);
  L.push(`}`);
  return L.join('\n');
}

export type CCodeTarget = 'BITFIELD' | 'DRIVERLIB';

/**
 * 生成 C 代码（Bit-Field 或 DriverLib 风格）。
 *
 * 这是「C 代码目标」的实现体；对外统一入口是 src/lib/targets/index.ts 的
 * generateCode()，它按 project.codeTarget 从注册表里挑目标。
 * 新增生成目标不需要改动本函数。
 */
export function produceC(input: ProjectState, hw: HardwareModel, target: CCodeTarget): GeneratedFile[] {
  // 把目标样式注入到项目视图上，下面所有 emitter 统一读 project.codeTarget
  const project: ProjectState = { ...input, codeTarget: target };
  const isCN = project.commentLang === 'CN';
  const t = makeCommenter(isCN);
  const style = project.codeTarget;

  const cLines: string[] = [];
  cLines.push(fileHeader(project, hw, 'epwm_config.c', isCN));
  cLines.push(style === 'BITFIELD' ? `#include "F28x_Project.h"` : `#include "driverlib.h"\n#include "device.h"`);
  cLines.push(`#include "epwm_config.h"`);
  if (project.modulationMode !== 'FIXED') cLines.push(`#include <math.h>`);
  cLines.push(``);
  cLines.push(`// ============================================================================`);
  cLines.push(`// ${t('GPIO 复用配置', 'GPIO pin-mux configuration')}`);
  cLines.push(`// ============================================================================`);
  cLines.push(gpioInit(hw, project));
  cLines.push(``);
  for (const c of hw.channels) {
    if (!c.cfg.enabled) continue;
    cLines.push(style === 'BITFIELD' ? bitfieldChannel(c, project, hw) : driverlibChannel(c, project, hw));
    cLines.push(``);
  }
  const isr = isrBlock(hw, project);
  if (isr) {
    cLines.push(isr);
    cLines.push(``);
  }

  const hLines: string[] = [];
  hLines.push(fileHeader(project, hw, 'epwm_config.h', isCN));
  hLines.push(`#ifndef EPWM_CONFIG_H`);
  hLines.push(`#define EPWM_CONFIG_H`);
  hLines.push(``);
  hLines.push(`#include <stdint.h>`);
  hLines.push(``);
  hLines.push(`#ifdef __cplusplus`);
  hLines.push(`extern "C" {`);
  hLines.push(`#endif`);
  hLines.push(``);
  hLines.push(`void EPWM_initGpio(void);`);
  for (const c of hw.channels) {
    if (!c.cfg.enabled) continue;
    hLines.push(`void EPWM_initCh${c.cfg.id}(void);   // ${c.cfg.name}`);
  }
  if (project.modulationMode !== 'FIXED') {
    hLines.push(``);
    hLines.push(`extern volatile float g_thetaRad;`);
    hLines.push(`__interrupt void epwm1_isr(void);`);
  }
  hLines.push(``);
  hLines.push(`#ifdef __cplusplus`);
  hLines.push(`}`);
  hLines.push(`#endif`);
  hLines.push(``);
  hLines.push(`#endif /* EPWM_CONFIG_H */`);

  const mLines: string[] = [];
  mLines.push(fileHeader(project, hw, 'main.c', isCN));
  mLines.push(style === 'BITFIELD' ? `#include "F28x_Project.h"` : `#include "driverlib.h"\n#include "device.h"`);
  mLines.push(`#include "epwm_config.h"`);
  if (project.modulationMode !== 'FIXED') mLines.push(`#include <math.h>`);
  mLines.push(``);
  mLines.push(mainBlock(hw, project));

  return [
    { name: 'main.c', language: 'c', content: mLines.join('\n') },
    { name: 'epwm_config.c', language: 'c', content: cLines.join('\n') },
    { name: 'epwm_config.h', language: 'h', content: hLines.join('\n') },
  ];
}

/** 把多个文件合并成一份（便于直接粘贴进 IDE 的小工程） */
export function mergeFiles(files: GeneratedFile[]): string {
  return files
    .map(f => `/* ======================== ${f.name} ======================== */\n\n${f.content}`)
    .join('\n\n');
}
